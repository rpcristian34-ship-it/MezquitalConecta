function translateChatMessage(msg, targetLang) {
  const sourceLang = msg.sourceLang || "es";
  const rawText = msg.text || "";
  if (!targetLang || sourceLang === targetLang) {
    return { displayText: rawText, isTranslated: false, sourceLang };
  }
  const key = msg.phraseKey || detectPhraseKey(rawText);
  if (key && phraseBank[key] && phraseBank[key][targetLang]) {
    return { displayText: phraseBank[key][targetLang], isTranslated: true, sourceLang };
  }

  let changedAny = false;
  const translatedTokens = rawText.split(/(\s+)/).map(token => {
    const match = token.match(/^([^a-zA-ZñÑáéíóúÁÉÍÓÚäëïöüÄËÏÖÜ'’]+)?([a-zA-ZñÑáéíóúÁÉÍÓÚäëïöüÄËÏÖÜ'’]+)([^a-zA-ZñÑáéíóúÁÉÍÓÚäëïöüÄËÏÖÜ'’]+)?$/);
    if (!match) return token;
    const [, lead = "", word, trail = ""] = match;
    const norm = normalizeWord(word);
    if (wordLexicon[norm] && wordLexicon[norm][targetLang]) {
      changedAny = true;
      let out = wordLexicon[norm][targetLang];
      if (word[0] === word[0].toUpperCase()) {
        out = out.charAt(0).toUpperCase() + out.slice(1);
      }
      return `${lead}${out}${trail}`;
    }
    return token;
  });

  if (changedAny) {
    return { displayText: translatedTokens.join(""), isTranslated: true, sourceLang };
  }

  return { displayText: rawText, isTranslated: false, sourceLang };
}

