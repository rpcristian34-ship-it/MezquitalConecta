function normalizeObfuscatedText(text) {
  const leetMap = {
    "0": "o", "1": "i", "!": "i", "|": "i", "3": "e", "4": "a", "@": "a",
    "5": "s", "$": "s", "7": "t", "+": "t", "8": "b", "9": "g"
  };
  const base = (text || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");

  let mapped = "";
  for (const ch of base) {
    mapped += leetMap[ch] || ch;
  }

  const lettersOnly = mapped.replace(/[^a-z0-9]+/g, " ").replace(/([a-z])\1+/g, "$1");
  const compactNoSpaces = mapped.replace(/[^a-z0-9]/g, "").replace(/([a-z])\1+/g, "$1");
  return { spaced: lettersOnly, compact: compactNoSpaces };
}

function hasBadWords(text) {
  const { spaced, compact } = normalizeObfuscatedText(text);
  const words = spaced.split(/\s+/).filter(Boolean);
  return BANNED_STEMS.some(stem => {
    const cleanStem = stem.normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/([a-z])\1+/g, "$1");
    const hitWord = words.some(w => w.startsWith(cleanStem));
    const hitCompact = compact.includes(cleanStem);
    return hitWord || hitCompact;
  });
}

